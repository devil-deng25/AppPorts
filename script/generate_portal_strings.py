#!/usr/bin/env python3
"""Generate the standalone portal's translations from the app string catalog."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KEYS = [
    "外部存储未连接，请连接后重试。",
    "好",
    "正在迁移或迁回应用数据，请等待完成后再打开。",
    "无法确认应用数据迁移状态，请打开 AppPorts 检查后重试。",
    "无法打开应用",
    "系统未能完成启动，请重试。",
]


def main():
    catalog = json.loads((ROOT / "AppPorts/Localizable.xcstrings").read_text())
    languages = re.findall(
        r'AppLanguageOption\(code: "([^"]+)"',
        (ROOT / "AppPorts/Models/AppLanguageOption.swift").read_text(),
    )
    lines = [
        "// Generated by script/generate_portal_strings.py from Localizable.xcstrings.",
        "// Shared with the standalone launcher; do not edit translations here.",
        "import Foundation", "", "enum PortalLocalizedStrings {",
        "    static let translations: [String: [String: String]] = [",
    ]
    for key in KEYS:
        lines.append(f"        {json.dumps(key, ensure_ascii=False)}: [")
        for language in languages:
            unit = catalog["strings"][key]["localizations"][language]["stringUnit"]
            if unit["state"] != "translated" or not unit["value"].strip():
                raise ValueError(f"Unfinished portal translation: {key} [{language}]")
            lines.append(f"            {json.dumps(language)}: {json.dumps(unit['value'], ensure_ascii=False)},")
        lines.append("        ],")
    lines += [
        "    ]", "",
        "    static func text(_ key: String, languages: [String] = Locale.preferredLanguages) -> String {",
        "        guard let values = translations[key] else { return key }",
        "        for preferred in languages {",
        '            let parts = preferred.replacingOccurrences(of: "_", with: "-").lowercased().split(separator: "-")',
        "            for count in stride(from: parts.count, through: 1, by: -1) {",
        '                let candidate = parts.prefix(count).joined(separator: "-")',
        "                if let language = values.keys.first(where: { $0.lowercased() == candidate }) {",
        "                    return values[language]!",
        "                }",
        "            }",
        '            if parts.first == "zh" {',
        '                let traditional = parts.contains("hant") || parts.contains("tw") || parts.contains("hk") || parts.contains("mo")',
        '                return values[traditional ? "zh-Hant" : "zh-Hans"] ?? values["en"] ?? key',
        "            }",
        "        }",
        '        return values["en"] ?? key',
        "    }", "}", "",
    ]
    (ROOT / "AppPorts/Utils/PortalLocalizedStrings.swift").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
